"""Measured OI-change cadence (step 6; answers Q-WS-1 / Q-NSE-1 from our own data).

  python3 -m engine.oi_cadence YYYY-MM-DD [YYYY-MM-DD ...] [--out docs/measured-oi-cadence.md]

For each instrument: the intervals (exchange-timestamp seconds) between consecutive OI changes
inside market hours (config market_hours). The first row of a day per instrument is a baseline
(prev_oi NULL), not a change. Intervals that overlap a recorded gap are excluded, not counted.
Phase 4 (owner decision): one COMBINED:<underlying> row per underlying with futures = the same statistics
over the union of its futures' change times (combined OI changes whenever any component changes).
"""

import argparse
import gzip
import math
import sqlite3
import statistics
import sys
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from .config import REPO, EngineConfig, load_config
from .provider import parse_master

IST = ZoneInfo("Asia/Kolkata")


def _rows(day_dir: Path, table: str, cols: str) -> list[tuple]:
    db = day_dir / "buffer.sqlite"
    if db.exists():
        c = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
        try:
            return c.execute(f"SELECT {cols} FROM {table}").fetchall()
        finally:
            c.close()
    import pyarrow.parquet as pq
    t = pq.ParquetDataset(day_dir / "parquet" / table).read().to_pydict()
    names = [c.strip() for c in cols.split(",")]
    conv = {"exchange_ts": "exchange_ts_ns"}
    data = [[(v // 1_000_000_000 if v is not None else None) for v in t[conv[n]]] if n in conv else t[n] for n in names]
    return list(zip(*data))


def nearest_rank(sorted_vals: list[float], q: float) -> float:
    return sorted_vals[max(0, math.ceil(q * len(sorted_vals)) - 1)]


def _stats(ts: list[int], gaps) -> dict:
    iv = [b - a for a, b in zip(ts, ts[1:]) if not any(gs < b and ge > a for gs, ge in gaps)]
    s = sorted(iv)
    return {"changes": len(ts), "intervals": len(s), "median_s": statistics.median(s) if s else None,
            "p90_s": nearest_rank(s, 0.9) if s else None, "max_s": s[-1] if s else None}


def cadence(day_dir: Path, cfg: EngineConfig, underlying_of: dict[int, str] | None = None) -> dict:
    """{token: stats}, plus {'COMBINED:<underlying>': stats} for futures tokens named in `underlying_of`."""
    day = datetime.fromisoformat(day_dir.name).date()
    t = lambda hhmm: datetime.combine(day, datetime.strptime(hhmm, "%H:%M").time(), IST).timestamp()  # noqa: E731
    lo, hi = t(cfg.get("market_hours.open")), t(cfg.get("market_hours.close"))
    gaps = [(s / 1e9, e / 1e9) for s, e in _rows(day_dir, "gaps", "start_ns, end_ns")
            if s is not None and e is not None]
    by_tok: dict[int, list[int]] = {}
    for tok, ex, prev in sorted(_rows(day_dir, "oi_changes", "token, exchange_ts, prev_oi"),
                                key=lambda r: (r[0], r[1] or 0)):
        if prev is not None and ex is not None and lo <= ex <= hi:
            by_tok.setdefault(tok, []).append(ex)
    out = {tok: _stats(ts, gaps) for tok, ts in by_tok.items()}
    groups: dict[str, list[int]] = {}
    for tok, ts in by_tok.items():
        if (underlying_of or {}).get(tok):
            groups.setdefault(underlying_of[tok], []).extend(ts)
    out.update({f"COMBINED:{u}": _stats(sorted(set(ts)), gaps) for u, ts in groups.items()})
    return out


DEFAULT_OUT = REPO / "docs" / "measured-oi-cadence.md"


def report(cfg: EngineConfig, dates: list[str], out: Path = DEFAULT_OUT) -> str:
    lines = ["# Measured OI-change cadence", "",
             f"Generated by `python3 -m engine.oi_cadence` from recorded tick data (config {cfg.version}). "
             f"Market hours {cfg.get('market_hours.open')}–{cfg.get('market_hours.close')} IST (F-NSE-1). "
             "Interval = seconds between consecutive OI changes by exchange timestamp; intervals overlapping a "
             "recorded gap are excluded. p90 = nearest rank. COMBINED:<underlying> rows (token `combined`) use the "
             "union of that underlying's futures' change times (same-second changes count once).", "",
             "| date | instrument | token | OI changes | intervals | median s | p90 s | max s |",
             "|---|---|---|---|---|---|---|---|"]
    for d in dates:
        day_dir = cfg.root / d
        mp = day_dir / "instruments.csv.gz"
        master = parse_master(gzip.decompress(mp.read_bytes())) if mp.exists() else []
        sym = {int(r["instrument_token"]): f"{r['exchange']}:{r['tradingsymbol']}" for r in master}
        und = {int(r["instrument_token"]): r["name"] for r in master if r["exchange"] == "NFO" and r["instrument_type"] == "FUT"}
        name = lambda k: k if isinstance(k, str) else sym.get(k, "?")  # noqa: E731
        for tok, c in sorted(cadence(day_dir, cfg, und).items(), key=lambda kv: (isinstance(kv[0], str), name(kv[0]))):
            lines.append(f"| {d} | {name(tok)} | {'combined' if isinstance(tok, str) else tok} | {c['changes']} | {c['intervals']} | "
                         f"{c['median_s']} | {c['p90_s']} | {c['max_s']} |")
    text = "\n".join(lines) + "\n"
    Path(out).write_text(text)
    return text


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="engine.oi_cadence")
    ap.add_argument("dates", nargs="+")
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--config", default=None)
    a = ap.parse_args(argv)
    print(report(load_config(a.config) if a.config else load_config(), a.dates, Path(a.out)), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
